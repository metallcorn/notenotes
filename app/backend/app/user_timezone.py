from __future__ import annotations

from datetime import datetime, timezone
from zoneinfo import ZoneInfo

# Единственное место в проекте, знающее часовой пояс пользователя — своей
# настройки для этого нет (CLAUDE.md: 2-10 пользователей, семья, один общий
# деплой, не мультитенантный SaaS с людьми в разных часовых поясах).
# Реальный найденный баг: дату/время без явного пояса — как их извлекает
# LLM из текста письма/билета, так и то, что модель сама формирует по
# просьбе "напомни в 9 утра" — раньше везде трактовали как UTC. Для
# пользователя в Польше (CEST, UTC+2 летом) это систематически сдвигало
# показанное время на 2 часа: письмо про встречу "17:30" в Познани
# превращалось в заметке в 19:30 на экране пользователя. ZoneInfo сам
# учитывает переход на летнее/зимнее время (CET/CEST) — не фиксированный
# сдвиг в часах.
DEFAULT_TZ = ZoneInfo("Europe/Warsaw")


def assume_default_timezone(dt: datetime) -> datetime:
    """Дата/время БЕЗ явного часового пояса — трактуем как местное время
    пользователя (DEFAULT_TZ), не UTC, и переводим в UTC для хранения.
    Уже tz-aware дату не трогаем — явный пояс всегда достовернее угадывания."""
    if dt.tzinfo is not None:
        return dt
    return dt.replace(tzinfo=DEFAULT_TZ).astimezone(timezone.utc)


def today_in_default_timezone() -> str:
    """Для промпта ассистента (Сегодняшняя дата: ...) — календарная дата по
    местному времени пользователя, не по UTC. Имеет значение у границы
    полуночи: в 00:30 по Варшаве уже наступил новый день локально, а по UTC
    (Варшава летом на 2 часа впереди) это ещё 22:30 предыдущего — "завтра"/
    "сегодня" в относительных формулировках резолвились бы не в тот день."""
    return datetime.now(DEFAULT_TZ).strftime("%Y-%m-%d")
