"""Одно событие, попавшее в базу дважды.

Живой случай 10.10: утренняя сводка пришла такой —

    📌 11:00 Marsz Kejterka в Познани — 🐕 Marsz Kejterka уже в эту субботу
    📌 11:00 Марш Кейтерка в Познани — 🐕 В Познани снова пройдёт Марш Кейтерка

Один и тот же собачий марш двумя строками. Причина не в ошибке кода:
poznan.pl написал о событии дважды (04.10 анонс, 08.10 напоминание,
разные адреса статей), это стало двумя заметками, и в каждой распознался
один и тот же час. Схлопывание по «та же дата + то же название»
(collect_agenda) их не поймало — названия честно разные, одно по-польски,
другое по-русски.

ПОЧЕМУ НЕ ПО ИСТОЧНИКУ. Первое, что хочется, — сравнить ссылки. Не
работает: статьи действительно разные (287699 и 287388). Общего
идентификатора у события нет вообще, он существует только в голове
читателя.

ПОЧЕМУ НЕ ПО СЛОВАМ. Второе желание — сравнить наборы слов после
транслитерации. Тоже не работает, и это видно на самом примере:
«Кейтерка» → keyterka, а польское Kejterka → kejterka; «Марш» → marsh
против Marsz. Ни одно ключевое слово не совпадает буквально.

ПОЭТОМУ — ПОХОЖЕСТЬ СТРОК ЦЕЛИКОМ, и порог не угадан, а ЗАМЕРЕН на
живых названиях из этой базы:

    дубликаты                                             разные события
    1.000  Налоги 08-2026 / Налоги 08-2026                 0.769  Фестиваль пива / Фестиваль кино
    0.917  Marsz Kejterka в Познани / Марш Кейтерка        0.615  Забрать права / Забрать посылку
    0.916  Срок истекает: Сервисная книжка / (копия)       0.593  Оплатить ZUS / Оплатить интернет
    0.863  Wizyta WUMP — Libelta / Визит в WUMP — Libelta  0.250  Встреча с врачом / Забрать посылку

Между 0.769 и 0.863 — зазор, порог 0.85 стоит в нём с запасом в обе
стороны.

ОБЯЗАТЕЛЬНОЕ УСЛОВИЕ — СОВПАДАЮЩЕЕ ВРЕМЯ, и без него порог опасен:
«Фестиваль 12 октября» и «Фестиваль 13 октября» похожи на 0.952, то есть
сильнее настоящего дубликата. Спасает именно то, что у них разное `at`.
Похожесть названий одна, без равенства времени, склеивала бы разные дни
одного и того же мероприятия — а это ровно то, чего человек от сводки не
простит.
"""

from __future__ import annotations

import re
from difflib import SequenceMatcher

from app.transliterate import _ru_to_lat

# См. замер в докстринге выше.
SAME_EVENT_RATIO = 0.85

_CYRILLIC_RE = re.compile(r"[а-яё]", re.IGNORECASE)
_WORD_RE = re.compile(r"\w+", re.UNICODE)


def normalize_title(title: str) -> str:
    """Название к одному виду: латиница, нижний регистр, без пунктуации.

    Кириллица транслитерируется, латиница остаётся как есть. Обратного
    направления (латиница → кириллица) здесь нет намеренно: на смешанных
    названиях вроде «Wizyta WUMP» оно даёт мусор («wизйта wумп») и роняет
    похожесть настоящего дубликата с 0.863 до 0.745, то есть ниже порога.
    """
    words = _WORD_RE.findall(title.lower())
    return " ".join(_ru_to_lat(w) if _CYRILLIC_RE.search(w) else w for w in words)


def same_event(title_a: str, title_b: str, *, ratio: float = SAME_EVENT_RATIO) -> bool:
    """Два названия описывают одно событие.

    Вызывать ТОЛЬКО для записей с одинаковым временем — см. докстринг
    модуля, без этого условия порог склеивает разные дни.
    """
    a, b = normalize_title(title_a), normalize_title(title_b)
    if not a or not b:
        return a == b
    if a == b:
        return True
    return SequenceMatcher(None, a, b).ratio() >= ratio
