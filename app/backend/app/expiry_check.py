"""Просроченная дата, поданная как действующая.

Реальный случай (диалог про замену прав, 2026-09-09). Пользователь прислал
данные мельдунка, ассистент прочитал в них срок и ответил:

    «Твоя текущая прописка ДЕЙСТВИТЕЛЬНА ДО 14 июня 2026 года.
     Для замены прав этот адрес подходит»

Дело было 9 сентября — прописка кончилась почти три месяца назад.
Пользователь заметил сам («так в смысле? она же просрочена уже»), но мог и
не заметить: пошёл бы подавать документы с недействительным мельдунком.

Текущая дата у модели в промпте есть с 2026-09-03. Она её просто не
сравнила — и это ровно тот случай, когда полагаться на рассуждение нельзя,
а проверить арифметику кодом дёшево.

Помечаем, а не исправляем: дата может быть выписана из документа верно, и
подменять текст ассистента опаснее, чем показать рядом честную пометку.
Тот же принцип, что у непроверенных чисел в «дорогих» темах.
"""

from __future__ import annotations

import re
from datetime import date

# Формулировки, после которых идёт СРОК ДЕЙСТВИЯ. Только они: просто дата в
# тексте («встреча была 14 июня») ничего не значит, и помечать её — шум.
# Русский, польский и английский — языки, на которых приходят документы.
_VALIDITY_PHRASES = (
    # Корень КОРОЧЕ полного слова — тот же урок, что с «создан» в детекторе
    # ложного «готово»: «действительна» и «действителен» это разные основы
    # («действительн» против «действител»), и первая версия пропускала
    # мужскую форму. Поймано собственным тестом на трёх документах в одном
    # ответе.
    r"действител\w*\s+до",
    r"действу\w+\s+до",
    r"срок\w*\s+действия\s+до",
    r"(?:годн\w*|годен)\s+до",
    r"истека\w+\s+",
    r"ważn\w*\s+do",
    r"do\s+dnia",
    r"valid\s+until",
    r"expires?\s+(?:on\s+)?",
)

_MONTHS = {
    "января": 1, "февраля": 2, "марта": 3, "апреля": 4, "мая": 5, "июня": 6,
    "июля": 7, "августа": 8, "сентября": 9, "октября": 10, "ноября": 11, "декабря": 12,
    "stycznia": 1, "lutego": 2, "marca": 3, "kwietnia": 4, "maja": 5, "czerwca": 6,
    "lipca": 7, "sierpnia": 8, "września": 9, "października": 10, "listopada": 11, "grudnia": 12,
}

_DATE_PATTERNS = (
    # 14 июня 2026 / 14 czerwca 2026
    r"(?P<d1>\d{1,2})\s+(?P<mon>[а-яёa-ząćęłńóśźż]+)\s+(?P<y1>\d{4})",
    # 14.06.2026 / 14-06-2026 / 14/06/2026
    r"(?P<d2>\d{1,2})[.\-/](?P<m2>\d{1,2})[.\-/](?P<y2>\d{4})",
    # 2026-06-14
    r"(?P<y3>\d{4})-(?P<m3>\d{1,2})-(?P<d3>\d{1,2})",
)

# Дата должна стоять СРАЗУ после формулировки: между «действительна до» и
# самой датой в живом тексте помещается разве что «**» разметки или
# предлог. Больший зазор ловил бы дату из соседнего предложения.
_CLAIM_RE = re.compile(
    r"(?:" + "|".join(_VALIDITY_PHRASES) + r")[\s*_«\"']{0,6}(?:"
    + "|".join(_DATE_PATTERNS) + r")",
    re.IGNORECASE,
)


def _to_date(match: re.Match[str]) -> date | None:
    g = match.groupdict()
    try:
        if g.get("mon"):
            month = _MONTHS.get(g["mon"].lower())
            if not month:
                return None
            return date(int(g["y1"]), month, int(g["d1"]))
        if g.get("d2"):
            return date(int(g["y2"]), int(g["m2"]), int(g["d2"]))
        if g.get("y3"):
            return date(int(g["y3"]), int(g["m3"]), int(g["d3"]))
    except ValueError:
        # 31 февраля и подобное — модель могла ошибиться в самой дате.
        # Сравнивать нечего, но и падать не за что.
        return None
    return None


def find_expired_claims(text: str, today: date) -> list[date]:
    """Даты, поданные как срок действия, но уже прошедшие.

    Возвращает список — в одном ответе может быть несколько документов.
    Сегодняшняя дата просроченной НЕ считается: срок «до 9 сентября»
    девятого сентября обычно ещё действует.
    """
    found: list[date] = []
    for match in _CLAIM_RE.finditer(text):
        parsed = _to_date(match)
        if parsed is not None and parsed < today and parsed not in found:
            found.append(parsed)
    return found
