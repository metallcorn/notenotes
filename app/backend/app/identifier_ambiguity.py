"""Чей это номер: предупреждение, когда в документе их несколько.

ЖИВОЙ СЛУЧАЙ 11.10. На прямой вопрос «Какой у меня PESEL?» ассистент
нашёл заметку «PIT Мужа» (совместная налоговая декларация, в ней номера
обоих супругов) и назвал ПЕРВЫЙ попавшийся — не тот, который спрашивали.
Уверенно, без оговорок.

В базе владельца на 11.10 лежит десять разных PESEL минимум восьми
человек: он сам, жена, трое прежних владельцев машины из договора
купли-продажи, ещё трое из пересылки «для ВНЖ доп». В первых шести
цифрах PESEL закодирована дата рождения, поэтому номера различимы: 900101
— это 01.01.1990, что совпадает с правами владельца; 920715 лежит в
файлах с именем жены. Ассистент ответил вторым.

ПОЧЕМУ НЕ ПРАВИЛОМ В ПРОМПТЕ. Правило «проверь, чей номер» в промпте
ничем не отличается от уже имеющихся — а они за сегодня трижды не
сработали (поиск в базе, кнопки, перекрытые даты). Модель не
подозревает о неоднозначности, пока ей не скажут.

ПОЭТОМУ — ФАКТ В РЕЗУЛЬТАТЕ ИНСТРУМЕНТА, как с подсказкой веб-поиска:
считаем номера в прочитанном тексте, и если их несколько РАЗНЫХ, кладём
рядом предупреждение. Срабатывает только при реальной неоднозначности:
в документе с одним номером никакого поля не появится.

ЧЕГО ЗДЕСЬ НЕТ. Мы не пытаемся определить, чей номер какой: это требует
разбора соседнего текста и имён, и ошибка тут хуже молчания. Мы говорим
модели ровно то, что знаем точно: «их несколько, разберись по тексту,
прежде чем называть».
"""

from __future__ import annotations

import re

# Одиннадцать цифр подряд — польский PESEL. Группы с пробелами тоже
# бывают: в PIT номер печатают по одной цифре в клетке
# («9 2 0 7 1 5 5 4 3 2 1»).
_PESEL_RE = re.compile(r"(?<!\d)(?:\d[ \t]?){10}\d(?!\d)")

# Ниже этого числа предупреждать не о чем.
_MIN_DISTINCT = 2


def distinct_identifiers(text: str) -> list[str]:
    """Разные одиннадцатизначные номера в тексте, в порядке появления."""
    seen: list[str] = []
    for match in _PESEL_RE.finditer(text or ""):
        digits = re.sub(r"\D", "", match.group(0))
        if digits not in seen:
            seen.append(digits)
    return seen


def ambiguity_warning(text: str) -> str | None:
    """Предупреждение для результата инструмента или None."""
    numbers = distinct_identifiers(text)
    if len(numbers) < _MIN_DISTINCT:
        return None
    return (
        f"ВНИМАНИЕ: в этом тексте {len(numbers)} разных одиннадцатизначных номеров (PESEL) — "
        "они принадлежат РАЗНЫМ людям. Прежде чем называть номер в ответе, определи по "
        "соседнему тексту, чей он именно; если по тексту не ясно — так и скажи и спроси, "
        "а не выбирай первый попавшийся."
    )
