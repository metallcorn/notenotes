# наборе, порог, где это начинает мешать — примерно 20-50 тулов. У нас 28
# — прямо в переходной зоне; поймано вживую на Llama 3.3 70B (Groq) —
# модель послабее иногда путает имя тула именно на полном наборе, хотя тот
