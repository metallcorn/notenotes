@router.delete("/{dialog_id}/messages/{message_id}", response_model=DialogOut)
async def delete_message(
    dialog_id: uuid.UUID,
    message_id: str,
    user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> DialogOut:
    item = await _get_dialog(db, user, dialog_id)
    records: list[dict] = list(item.properties.get("messages", []))

    index = next((i for i, r in enumerate(records) if r["id"] == message_id), None)
    if index is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Сообщение не найдено")

    target = records[index]
    if target["role"] == "tool":
        raise HTTPException(
            status.HTTP_400_BAD_REQUEST, "Нельзя удалить результат инструмента отдельно — удали связанную реплику"
        )

    # Реплика ассистента с tool_calls тянет за собой свои "tool"-записи —
    # иначе при следующей отправке история для LLM была бы битой (висящий
    # tool_call без результата).
    tool_call_ids = {tc["id"] for tc in target.get("tool_calls", [])}
    remaining = [
        r
        for i, r in enumerate(records)
        if i != index and not (r["role"] == "tool" and r.get("tool_call_id") in tool_call_ids)
    ]

    item.properties = {**item.properties, "messages": remaining}
    item.content = _flatten_transcript(remaining)
    await db.commit()
    await db.refresh(item)
    await realtime.notify_space(item.space_id, "dialogs")
    return _serialize(item)


async def run_dialog_turn(db: AsyncSession, user: User, item: Item, content: str) -> list[dict]:
    """Один ход агентного цикла над диалогом `item`: добавляет реплику
    пользователя, гоняет LLM+тулы до финального ответа или потолка
    итераций, коммитит и уведомляет по WS. Общее ядро для HTTP-эндпоинта
    ниже (send_message) и Telegram-моста (app/telegram_bot.py) — та же
    логика должна вести себя одинаково в обоих местах, а не дублироваться."""
    records: list[dict] = list(item.properties.get("messages", []))
    # Проверено где-то РАНЬШЕ в этом диалоге (не обязательно в этом ходу) —
    # реальный баг, пойманный ролплей-тестом: гейт ниже требовал list_folders
    # именно в ТЕКУЩЕМ ходу, поэтому когда пользователь на СЛЕДУЮЩЕЙ реплике
    # подтверждал "без папки" в ответ на уже заданный вопрос, гейт всё равно
    # блокировал повторно (list_folders в этом новом ходу не звался — модель
    # ведь уже знала ответ из истории) — модель застревала и один раз молча
    # положила заметку не туда, соврав, что "не получилось без папки".
    # Список папок за один диалог почти никогда не меняется, поэтому "хоть
    # раз в этом диалоге" — достаточная и куда менее ломкая проверка, чем
    # "именно в этом ходу".
    folders_checked_earlier = any(
        tc.get("name") == "list_folders" for r in records if r.get("role") == "assistant" for tc in r.get("tool_calls", [])
    )
    # Первое сообщение в этом диалоге, и ни одного факта в памяти ещё нет —
    # см. ONBOARDING_PROMPT_FRAGMENT. Гейтится по фактам, не по разовому
    # флагу "уже спрашивали": как только появится хотя бы один remember_fact,
    # условие само перестанет срабатывать в новых диалогах.
    is_fresh_start = not records
    records.append({"id": str(uuid.uuid4()), "role": "user", "content": content, "created_at": _now_iso()})

    # Реальный баг, пойманный ролплей-тестом: _named_list_owner_mismatch
    # ниже сначала сравнивал имя только с ТЕКУЩИМ сообщением — а обычный
    # диалог многоходовый: "добавь Ульяне крем" → "какой именно?" →
    # "NYX ...". Имя было во ВТОРОМ ходу назад, не в этом — гейт ложно
    # блокировал ответ на уточняющий вопрос. Берём последние несколько
    # реплик ПОЛЬЗОВАТЕЛЯ (не ассистента — его текст не показатель того,
    # что имел в виду человек), не только последнюю.
    recent_user_text = " ".join(
        r["content"] for r in records[-8:] if r.get("role") == "user" and r.get("content")
    )

    if item.title in ("", "Новый диалог"):
        item.title = content[:60]

    settings = get_settings()
    disabled_tool_names = set(user.disabled_tools)
    all_tool_definitions = get_tool_definitions(disabled=disabled_tool_names)

    # Мини-чат "спроси ассистента в заметке" (NoteAssistantModal.tsx на
    # фронте) — привязан к конкретной заметке через scoped_item_id в
    # properties (см. create_dialog). Тулы урезаны до чтения/поиска — этот
    # чат не должен уметь молча создать/поменять/удалить ЧТО-ТО ДРУГОЕ,
    # только найти информацию и предложить её пользователю; применяет в
    # саму заметку сам пользователь кнопкой на фронте, не тул. Контент
    # заметки читается заново на каждом ходу (не один раз при создании
    # диалога) — пользователь может продолжать её редактировать между
    # репликами чата.
    scoped_item_id_raw = item.properties.get("scoped_item_id")
    scoped_note_context: str | None = None
    if scoped_item_id_raw:
        scoped_item = await db.get(Item, uuid.UUID(str(scoped_item_id_raw)))
        # Реальный найденный баг security-ревью: доступ к заметке проверялся
        # только один раз, при создании диалога (create_dialog). Если
        # заметку потом переносят в другой спейс (POST /items/{id}/move),
        # этот диалог продолжал бы читать её АКТУАЛЬНОЕ содержимое каждый
        # ход и вписывать в промпт модели, даже если пользователь диалога
        # больше не имеет доступа к новому спейсу заметки — утечка контента
        # через ответы ассистента в обход обычной проверки прав.
        scoped_access_ok = False
        if scoped_item is not None:
            try:
                await ensure_space_access(db, scoped_item.space_id, user.id)
                scoped_access_ok = True
            except HTTPException:
                scoped_access_ok = False
        if scoped_item is not None and scoped_item.deleted_at is None and scoped_access_ok:
            tool_definitions = [d for d in all_tool_definitions if d.name in _SCOPED_TOOL_NAMES]
            scoped_selection = str(item.properties.get("scoped_selection") or "").strip()
            focus_line = (
                f'\n\nПользователь выделил в заметке именно этот фрагмент перед тем, как открыть '
                f'этот чат: «{scoped_selection}» — фокусируйся на нём, если явно не попросит шире.'
                if scoped_selection
                else ""
            )
            scoped_note_context = (
                f"Этот диалог — вспомогательный, открыт прямо из заметки «{scoped_item.title}» "
                f"(id={scoped_item.id}), пользователь работает над ней сейчас. Текущее содержимое "
                f"заметки:\n\n"
                f"---\n{scoped_item.content}\n---\n"
                f"{focus_line}\n\n"
                "Твоя задача — найти/уточнить информацию по просьбе пользователя (в вебе через "
                "web_search/read_website, среди других его заметок через search_base/get_note) и "
                "предложить, чем обогатить эту заметку или как обновить её часть. У тебя НЕТ тулов "
                "изменения самой заметки (create_note/update_note и т.п.) — это осознанно, не "
                "пытайся и не извиняйся за это: результат применяет сам пользователь кнопкой "
                "«Вставить в заметку» под твоим ответом, поэтому отвечай текстом, который имеет "
                "смысл вставить как есть — без вступлений вроде «Вот что я нашёл», сразу суть.\n\n"
                "Исключение — create_reminder ТЕБЕ ДОСТУПЕН прямо здесь (ничего не перезаписывает, "
                "поэтому не под тем же ограничением): если пользователь просит напоминание по теме "
                "разговора — создавай его с item_id="
                f'"{scoped_item.id}", чтобы клик по уведомлению открывал именно эту заметку. Как и '
                "всегда для create_reminder — сначала спроси, нужно ли и на какое время, не создавай "
                "молча."
            )
        else:
            tool_definitions = []
    if scoped_note_context is None:
        already_used_tools = {
            tc.get("name") for r in records if r.get("role") == "assistant" for tc in r.get("tool_calls", []) if tc.get("name")
        }
        relevant_names = _relevant_tool_names(
            {d.name for d in all_tool_definitions}, recent_user_text, already_used_tools
        )
        tool_definitions = [d for d in all_tool_definitions if d.name in relevant_names]
    ctx = ToolContext(db=db, user_id=user.id, space_id=item.space_id)
    web_search_calls = 0
    max_web_search_calls = settings.web_search_max_calls_per_turn
    verified_urls: set[str] = set()
    used_web_search = False
    used_advanced_web_search = False
    folders_checked_this_turn = folders_checked_earlier
    list_folders_names: list[str] = []
    list_candidates_seen_this_turn: dict[str, str] = {}
    linked_entries_seen_this_turn: list[tuple[str, str]] = []

    if not settings.llm_api_key:
        records.append(
            {
                "id": str(uuid.uuid4()),
                "role": "assistant",
                "content": "Ассистент ещё не настроен: не задан ключ LLM-провайдера (LLM_API_KEY).",
                "created_at": _now_iso(),
            }
        )
        item.properties = {**item.properties, "messages": records}
        item.content = _flatten_transcript(records)
        await db.commit()
        await db.refresh(item)
        return records

    llm_client = get_llm_client(user.llm_provider)

    memories_result = await db.execute(
        select(AssistantMemory.content).where(AssistantMemory.user_id == user.id).order_by(AssistantMemory.created_at)
    )
    memory_facts = [row[0] for row in memories_result.all()]
    enabled_tool_names = {d.name for d in tool_definitions}
    system_prompt = _build_system_prompt(
        memory_facts,
        user.custom_instructions,
        enabled_tool_names,
        disabled_tool_names,
        is_fresh_start and not memory_facts and scoped_note_context is None,
    )
    if scoped_note_context:
        system_prompt += "\n\n" + scoped_note_context
    tool_call_leak_retried = False

    for _ in range(MAX_TOOL_ITERATIONS):
        try:
            response = await llm_client.chat(_to_llm_messages(records, system_prompt), tool_definitions)
        except (httpx.HTTPError, EmptyLLMResponseError):
            logger.exception("Ошибка обращения к LLM-провайдеру")
            records.append(
                {
                    "id": str(uuid.uuid4()),
                    "role": "assistant",
                    "content": "Не получилось получить ответ от LLM-провайдера — попробуй ещё раз чуть позже.",
                    "created_at": _now_iso(),
                }
            )
            break
        assistant_msg = response.message

        # Изредка модель вместо настоящего tool_call пишет его как обычный
        # текст ("create_calendar_event {...}") — реального вызова не
        # происходит (событие не создаётся), а пользователь видит в чате
        # сырой JSON вместо результата. Поймано вживую на реальном разговоре
        # (репорт пользователя: "ссылка на календарь не создалась"). Раз —
        # молча повторяем тот же запрос без добавления в историю (обычно
        # помогает), не удалось второй раз — показываем честную ошибку
        # вместо мусора.
        if not assistant_msg.tool_calls and _looks_like_leaked_tool_call(assistant_msg.content, enabled_tool_names):
            logger.warning("Похоже на утёкший tool_call текстом вместо настоящего вызова: %r", assistant_msg.content[:200])
            if not tool_call_leak_retried:
                tool_call_leak_retried = True
                continue
            records.append(
                {
                    "id": str(uuid.uuid4()),
                    "role": "assistant",
                    "content": "Не получилось выполнить действие — попробуй переформулировать запрос.",
                    "created_at": _now_iso(),
                }
            )
            break

        # suggest_replies — не настоящий тул с побочным эффектом, а разметка
        # для UI (чипы вместо свободного текста). Не кладём его в tool_calls
        # (не показываем как техническую "🔧 вызвал тул" строку) и не зовём
        # dispatch — сразу после него всегда конец хода, ждём клика/ввода.
        real_tool_calls = [tc for tc in assistant_msg.tool_calls if tc.name != "suggest_replies"]
        suggest_calls = [tc for tc in assistant_msg.tool_calls if tc.name == "suggest_replies"]

        assistant_record: dict = {
            "id": str(uuid.uuid4()),
            "role": "assistant",
            "content": _append_missing_entry_links(
                _strip_unverified_links(assistant_msg.content, verified_urls), linked_entries_seen_this_turn
            ),
            "created_at": _now_iso(),
        }
        if real_tool_calls:
            assistant_record["tool_calls"] = [
                {"id": tc.id, "name": tc.name, "arguments": tc.arguments, **({"metadata": tc.metadata} if tc.metadata else {})}
                for tc in real_tool_calls
            ]
        elif assistant_record["content"].strip():
            # Модель иногда отвечает по памяти о более раннем результате
            # search_base/get_note вместо повторного вызова в этом ходу —
            # даже после явной инструкции в промпте звать тул заново
            # (наблюдалось дважды подряд вживую на реальном диалоге, промпт
            # не гарантия поведения модели). Карточки на фронте
            # (TicketResultCards/NoteResultLinks/LinkPreviewResultCards)
            # читают tool_calls именно текущего сообщения — без этого ответ
            # выглядел бы без единой рабочей ссылки/кнопки, при том что
            # данные для карточки уже реально есть в истории диалога.
            #
            # display_tool_calls, НЕ tool_calls: реальная поломка, пойманная
            # вживую — _to_llm_messages читает именно "tool_calls" и
            # реконструирует по нему assistant-сообщение с tool_calls для
            # LLM API, а Mistral (как и весь OpenAI-совместимый протокол)
            # требует, чтобы такое сообщение было НЕМЕДЛЕННО продолжено
            # tool-сообщениями с результатами — которых тут нет (настоящего
            # вызова не было). Итог был 400 Bad Request на КАЖДЫЙ следующий
            # ход этого диалога, включая уже сохранённые в БД записи —
            # ломало реальный диалог пользователя намертво. display_tool_calls
            # — отдельное поле, которое _to_llm_messages не читает вовсе
            # (см. ниже), только фронт для отрисовки карточек.
            for prior in reversed(records):
                if prior.get("role") == "assistant" and prior.get("tool_calls"):
                    assistant_record["display_tool_calls"] = prior["tool_calls"]
                    break
        if suggest_calls:
            options: list[str] = []
            for tc in suggest_calls:
                options.extend(str(o).strip() for o in tc.arguments.get("options", []) if str(o).strip())
            assistant_record["suggested_replies"] = options
        records.append(assistant_record)

        if not assistant_msg.tool_calls:
            break

        for tc in real_tool_calls:
            if tc.name == "web_search":
                web_search_calls += 1
                if web_search_calls > max_web_search_calls:
                    result: dict = {"error": "Лимит веб-поиска на этот ход исчерпан"}
                else:
                    used_web_search = True
                    if str(tc.arguments.get("depth", "basic")).strip().lower() == "advanced":
                        used_advanced_web_search = True
                    result = await dispatch(tc.name, ctx, tc.arguments, disabled=disabled_tool_names)
                    for search_result in result.get("results", []) or []:
                        url = search_result.get("url")
                        if url:
                            verified_urls.add(url)
                    # include_images=true — те же реальные URL с Tavily, тот
                    # же принцип "пришло из тула, не выдумка модели", просто
                    # это markdown-картинка ![]() (_strip_unverified_links
                    # проверяет URL в скобках независимо от ! перед ними).
                    for image in result.get("images", []) or []:
                        url = image.get("url")
                        if url:
                            verified_urls.add(url)
            elif tc.name == "list_folders":
                result = await dispatch(tc.name, ctx, tc.arguments, disabled=disabled_tool_names)
                folders_checked_this_turn = True
                list_folders_names = [f["name"] for f in result.get("folders", []) if f.get("name")]
            elif tc.name == "search_base":
                result = await dispatch(tc.name, ctx, tc.arguments, disabled=disabled_tool_names)
                for found in result.get("results", []) or []:
                    if found.get("material_type") == "list" and found.get("id"):
                        list_candidates_seen_this_turn[found["id"]] = found.get("title", "")
            elif (
                tc.name in ("create_note", "create_list")
                and not str(tc.arguments.get("folder_id") or "").strip()
                and not folders_checked_this_turn
            ):
                # Промпт и раньше просил проверять list_folders перед
                # созданием без явной папки (см. SYSTEM_PROMPT_BASE) — но
                # это оказалось ненадёжно: реальный случай, когда модель
                # молча создала заметку в корне спейса «Личное», хотя
                # тематически подходящей папки не было вовсе и стоило бы
                # ПРЕДЛОЖИТЬ создать новую («Мероприятия» для афиши
                # фестиваля) — модель просто не позвала list_folders в этом
                # ходу и не узнала, что вариантов нет. Дословное соответствие
                # промпту не гарантия поведения модели (тот же урок, что и
                # с повторным вызовом get_note выше) — здесь принудительно
                # не даём создать без проверки, вместо ещё одной попытки
                # усилить формулировку.
                result = {
                    "error": (
                        "Сначала вызови list_folders — folder_id не передан, а папки в этом спейсе ещё "
                        "не проверены нигде в этом диалоге. Проверь, нет ли уже подходящей по теме папки "
                        "(не обязательно совпадающей по названию буквально), и вызови создание снова: "
                        "либо с folder_id найденной папки (после подтверждения пользователем), либо явно "
                        "без folder_id, если подходящей папки нет и корень спейса — осознанный выбор, а "
                        "не пропущенная проверка."
                    )
                }
            elif (
                tc.name == "update_note"
                and tc.arguments.get("content") is not None
                and (
                    missing_attachments := await _missing_attachments_on_update(
                        ctx.db, ctx.user_id, tc.arguments.get("item_id"), str(tc.arguments["content"])
                    )
                )
            ):
                result = {
                    "error": (
                        f"В текущем содержимом заметки есть вложение(я) ({', '.join(missing_attachments)}), "
                        f"которых нет в новом content — update_note заменяет содержимое ЦЕЛИКОМ, не "
                        f"добавляет к старому. Похоже, при переписывании текста вложение потерялось. "
                        f"Вызови get_note(item_id=...), возьми его content КАК ЕСТЬ (включая все теги "
                        f"вложений — ![](url), <video>, <audio>, data-url=...), допиши к нему нужное и "
                        f"вызови update_note снова с ПОЛНЫМ содержимым, ничего не пропуская."
                    )
                }
            elif tc.name == "add_list_entry" and (
                owner := await _named_list_owner_mismatch(
                    ctx.db, ctx.user_id, tc.arguments.get("list_id"), recent_user_text
                )
            ):
                result = {
                    "error": (
                        f"Этот список назван в честь конкретного человека ({owner}) — это ЕГО/ЕЁ личный "
                        f"список, не общая категория. Пользователь не упомянул «{owner}» в своём "
                        f"сообщении для этого предмета — не факт, что предмет для {owner}. Спроси через "
                        f"suggest_replies, в какой список добавить (этот, или другой/новый), прежде чем "
                        f"вызывать add_list_entry снова."
                    )
                }
            elif tc.name == "add_list_entry" and (
                other_lists := _ambiguous_list_pick(
                    tc.arguments.get("list_id"), list_candidates_seen_this_turn, recent_user_text
                )
            ):
                result = {
                    "error": (
                        f"search_base в этом ходу нашёл несколько подходящих по теме списков "
                        f"({'; '.join(other_lists)} и выбранный) — пользователь явно не назвал, какой "
                        f"именно имел в виду. Выбирать самому по теме нельзя: можно записать не в тот "
                        f"список. Спроси через suggest_replies, какой из найденных списков имелся в виду, "
                        f"прежде чем вызывать add_list_entry снова."
                    )
                }
            else:
                result = await dispatch(tc.name, ctx, tc.arguments, disabled=disabled_tool_names)

            # Реальный найденный баг: _strip_unverified_links ниже считал
            # "верифицированной" только ссылку из web_search этого хода —
            # ссылка внутри пункта СПИСКА или содержимого ЗАМЕТКИ (get_list/
            # get_note/search_base — уже реальные данные из базы, не
            # выдумка модели) резалась точно так же, как придуманная. Итог:
            # модель пересказывала список покупок с настоящими
            # markdown-ссылками на товары, а в чате они превращались в
            # голый текст. Любая ссылка, реально пришедшая В РЕЗУЛЬТАТЕ
            # тула (не в аргументах вызова — те могла написать сама модель),
            # достаточно "верифицирована" для показа кликабельной.
            for _, found_url in _MARKDOWN_LINK_RE.findall(json.dumps(result, ensure_ascii=False)):
                verified_urls.add(found_url)
            if tc.name == "get_list":
                for entry in result.get("entries", []) or []:
                    link = _extract_entry_link(str(entry.get("text", "")))
                    if link:
                        linked_entries_seen_this_turn.append(link)

            records.append(
                {
                    "id": str(uuid.uuid4()),
                    "role": "tool",
                    "tool_call_id": tc.id,
                    "name": tc.name,
                    "content": json.dumps(result, ensure_ascii=False),
                    "created_at": _now_iso(),
                }
            )

        if suggest_calls:
            break
    else:
        records.append(
            {
                "id": str(uuid.uuid4()),
                "role": "assistant",
                "content": "Не удалось завершить ответ за отведённое число шагов — попробуй переформулировать запрос.",
                "created_at": _now_iso(),
            }
        )

    # Модель не всегда помнит предложить более глубокий поиск сама (иногда
    # просто пишет вопрос текстом вместо вызова suggest_replies) — не
    # полагаемся только на промпт, гарантируем чип кодом, если в этом ходе
    # был хотя бы один web_search и ни один не был depth=advanced.
    if used_web_search and not used_advanced_web_search and records and records[-1]["role"] == "assistant":
        chip = "Поискать глубже"
        existing = records[-1].get("suggested_replies") or []
        if chip not in existing:
            records[-1]["suggested_replies"] = [*existing, chip]

    # Тот же принцип, для другого реального случая, пойманного ролплей-
    # тестом: после list_folders модель дважды подряд в одном диалоге
    # написала варианты папок голым текстом вместо suggest_replies (в
    # тексте даже затесались невидимые символы U+2060 — похоже на
    # артефакт генерации самой модели, не нашего кода) — пользователь
    # получал список названий папок без единого клика. Промпт это уже
    # прямым текстом запрещает ("никогда не пиши варианты просто
    # текстом"), но это тот самый случай, когда дословное соответствие
    # промпту не гарантия — подстраховываем кодом. Условие узкое: список
    # папок в этом ходу запрашивался, финальный ответ — чистый текст без
    # tool_calls и без собственных suggested_replies (иначе бы не трогали
    # то, что модель уже честно предложила сама). Реальные названия папок,
    # которые модель упомянула текстом, вытаскиваем подстрокой — их же
    # словами, а не гадаем — и всегда добавляем «Без папки» как честный
    # запасной вариант.
    if (
        list_folders_names
        and records
        and records[-1]["role"] == "assistant"
        and not records[-1].get("tool_calls")
        and not records[-1].get("suggested_replies")
        and records[-1]["content"].strip()
    ):
        text_lower = records[-1]["content"].lower()
        # Регистронезависимо: модель нередко пишет название с большой буквы
        # в начале строки/**жирным** ("**Блог (жабы)**"), даже если реальное
        # имя папки — со строчной ("блог (жабы)") — точное совпадение
        # регистра теряло бы такие варианты.
        mentioned = [name for name in list_folders_names if name.lower() in text_lower]
        if mentioned or "папк" in text_lower:
            options = [*mentioned, "Без папки"]
            records[-1]["suggested_replies"] = options

    # Сигнал для мониторинга между раундами ролплей-тестирования, а не для
    # рантайм-поведения — фикс выше закрывает только форму "после
    # list_folders". Та же болезнь может проявиться в любом другом месте
    # (например "напоминание нужно?" текстом вместо suggest_replies), где
    # у нас нет списка реальных сущностей, чтобы детерминированно
    # восстановить чипы — только логируем, чтобы накапливать частоту по
    # логам между прогонами, а не полагаться только на то, что очередной
    # ручной/ролплей-раунд случайно наткнётся на конкретный пример.
    if (
        records
        and records[-1]["role"] == "assistant"
        and not records[-1].get("tool_calls")
        and not records[-1].get("suggested_replies")
        and _looks_like_missed_choice(records[-1]["content"])
    ):
        logger.warning(
            "Похоже на вариант выбора текстом без suggest_replies (диалог %s): %r",
            item.id,
            records[-1]["content"][:200],
        )

    item.properties = {**item.properties, "messages": records}
    item.content = _flatten_transcript(records)
    await db.commit()
    await db.refresh(item)
    await realtime.notify_space(item.space_id, "dialogs")
    return records


@router.post("/{dialog_id}/messages", response_model=DialogOut)
async def send_message(
    dialog_id: uuid.UUID,
    payload: MessageCreate,
    user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
) -> DialogOut:
    item = await _get_dialog(db, user, dialog_id)
    content = payload.content.strip()
    if not content:
        raise HTTPException(status.HTTP_400_BAD_REQUEST, "Пустое сообщение")
    await run_dialog_turn(db, user, item, content)
    return _serialize(item)
