# Вынесено отдельной чистой функцией (не инлайном внутри run_dialog_turn) —
# та дёргает реальный LLM-провайдер и намеренно не покрыта тестами (см.
# докстринг test_dialogs.py), а вот построение самого текста контекста —
# обычная строковая логика, ошибиться в подсчёте бюджета/обрезке легко и
# незаметно. Тестируется напрямую, без БД и без LLM.
_FOLDER_CONTEXT_PREVIEW_CHARS = 300
_FOLDER_CONTEXT_BUDGET_CHARS = 6000


def _build_folder_context(folder: Folder, folder_items: list[Item]) -> str:
    lines: list[str] = []
    total = 0
    shown = 0
    for fi in folder_items:
        preview = " ".join((fi.content or "").split())[:_FOLDER_CONTEXT_PREVIEW_CHARS]
        entry = f"- «{fi.title}» (id={fi.id}): {preview}"
        if shown > 0 and total + len(entry) > _FOLDER_CONTEXT_BUDGET_CHARS:
            break
        lines.append(entry)
        total += len(entry)
        shown += 1
    remainder_note = (
        f"\n\n...и ещё {len(folder_items) - shown} заметок в этой папке, здесь не показаны целиком "
        "(список выше неполный) — используй get_note/search_base, если нужно заглянуть в конкретную "
        "из них подробнее."
        if shown < len(folder_items)
        else ""
    )
    return (
        f"Этот диалог — вспомогательный, открыт из папки «{folder.name}» (id={folder.id}) — "
        "пользователь хочет обсудить заметки внутри неё как единое целое, не что-то ещё в "
        f"приложении, если явно не попросит шире. Заметки в этой папке ({len(folder_items)}):\n\n"
        + "\n".join(lines) + remainder_note +
        "\n\nИщи в вебе (web_search/read_website) или среди ДРУГИХ заметок пользователя "
        "(search_base/get_note) только если пользователь явно попросит посмотреть шире папки."
    )


# Реальный найденный случай: два хода одного диалога, наложившиеся друг на
# друга (например, повторный клик/запрос, пока первый ещё не закончился —
# агентный цикл с web_search может идти долго), гонялись параллельно НА
# ОДНОМ И ТОМ ЖЕ item.properties["messages"] — каждый читает records в
# начале, копит его в памяти и переписывает поле ЦЕЛИКОМ в конце.
# Последний, кто закоммитил, стирает всё, что успел дописать первый —
# конкретно найдено: ответ ассистента исчезал целиком, хотя реально
# генерировался (несовпадение item.content и messages — content длиннее,
# чем то, что реально осталось в messages, — прямое доказательство). Лок
# на dialog_id сериализует ходы ОДНОГО диалога — второй запрос дождётся
# первого и прочитает уже актуальный records, а не гонится с ним.
_dialog_turn_locks: dict[uuid.UUID, asyncio.Lock] = {}


def _get_dialog_turn_lock(dialog_id: uuid.UUID) -> asyncio.Lock:
    lock = _dialog_turn_locks.get(dialog_id)
    if lock is None:
        lock = asyncio.Lock()
        _dialog_turn_locks[dialog_id] = lock
    return lock


async def run_dialog_turn(
    db: AsyncSession, user: User, item: Item, content: str, client_timezone: str | None = None
) -> list[dict]:
    """Один ход агентного цикла над диалогом `item` — тонкая обёртка вокруг
    _run_dialog_turn_locked, сериализующая параллельные ходы ОДНОГО и того
    же диалога (см. комментарий у _dialog_turn_locks выше).

    client_timezone — живой пояс из браузера (send_message, заголовок
    X-Client-Timezone) или домашний пояс пользователя как замена для
    Telegram (telegram_bot.py, живого браузера там нет — см.
    app/user_timezone.py)."""
    async with _get_dialog_turn_lock(item.id):
        return await _run_dialog_turn_locked(db, user, item, content, client_timezone)


async def _run_dialog_turn_locked(
    db: AsyncSession, user: User, item: Item, content: str, client_timezone: str | None = None
) -> list[dict]:
    """Один ход агентного цикла над диалогом `item`: добавляет реплику
    пользователя, гоняет LLM+тулы до финального ответа или потолка
    итераций, коммитит и уведомляет по WS. Общее ядро для HTTP-эндпоинта
    ниже (send_message) и Telegram-моста (app/telegram_bot.py) — та же
    логика должна вести себя одинаково в обоих местах, а не дублироваться."""
    records: list[dict] = list(item.properties.get("messages", []))
    # Проверено где-то РАНЬШЕ в этом диалоге (не обязательно в этом ходу) —
    # реальный баг, пойманный ролплей-тестом: гейт ниже требовал list_folders
    # именно в ТЕКУЩЕМ ходу, поэтому когда пользователь на СЛЕДУЮЩЕЙ реплике
    # подтверждал "без папки" в ответ на уже заданный вопрос, гейт всё равно
    # блокировал повторно (list_folders в этом новом ходу не звался — модель
    # ведь уже знала ответ из истории) — модель застревала и один раз молча
    # положила заметку не туда, соврав, что "не получилось без папки".
    # Список папок за один диалог почти никогда не меняется, поэтому "хоть
    # раз в этом диалоге" — достаточная и куда менее ломкая проверка, чем
    # "именно в этом ходу".
    folders_checked_earlier = any(
        tc.get("name") == "list_folders" for r in records if r.get("role") == "assistant" for tc in r.get("tool_calls", [])
    )
    # Первое сообщение в этом диалоге — см. ONBOARDING_PROMPT_FRAGMENT.
    # Дополнительное условие "новичок ли пользователь вообще" считается
    # ниже, уже с доступом к БД (см. is_new_user).
    is_fresh_start = not records
    records.append({"id": str(uuid.uuid4()), "role": "user", "content": content, "created_at": _now_iso()})

    # Реальный баг, пойманный ролплей-тестом: _named_list_owner_mismatch
    # ниже сначала сравнивал имя только с ТЕКУЩИМ сообщением — а обычный
    # диалог многоходовый: "добавь Алине крем" → "какой именно?" →
    # "NYX ...". Имя было во ВТОРОМ ходу назад, не в этом — гейт ложно
    # блокировал ответ на уточняющий вопрос. Берём последние несколько
    # реплик ПОЛЬЗОВАТЕЛЯ (не ассистента — его текст не показатель того,
    # что имел в виду человек), не только последнюю.
    recent_user_text = " ".join(
        r["content"] for r in records[-8:] if r.get("role") == "user" and r.get("content")
    )
    # Считаем один раз: используется и при сборке промпта (условный
    # фрагмент), и в цикле (код-гарантия против непроверенных чисел).
    high_stakes_topic = _is_high_stakes_topic(recent_user_text)

    if item.title in ("", "Новый диалог"):
        item.title = content[:60]

    # Реальная жалоба: реплика пользователя нигде не была видна на сервере,
    # пока не завершится ВЕСЬ ход (агентный цикл иногда занимает долго) —
    # свернул вкладку/перезагрузил посреди ожидания, вернулся — не
    # понятно, отправилось сообщение или нет ("как будто ничего не было"),
    # а ответ потом появляется как будто ниоткуда. Коммитим реплику
    # пользователя сразу, отдельно от финального коммита в конце этой же
    # функции (там же допишется ответ ассистента поверх этих же records) —
    # не идеальная атомарность (сервер может упасть ровно между этим
    # коммитом и концом хода, реплика останется без ответа), но строго
    # лучше прежнего "либо всё разом, либо ничего", и снимает основную
    # путаницу: GET /dialogs/{id} сразу покажет, что сообщение дошло.
    #
    # Реальный найденный баг (пойман через прямое чтение из БД, не через
    # тот же ORM-объект): list(records), НЕ records как есть — records
    # мутируется дальше по ходу функции (записи дописываются в тот же
    # list), а этот commit — не последний. Если положить сюда САМ records,
    # "messages" в item.properties и то, что будет дальше дописываться в
    # records — окажутся ОДНИМ И ТЕМ ЖЕ list-объектом по ссылке; когда
    # ниже произойдёт повторное присваивание item.properties = {...,
    # "messages": records}, SQLAlchemy сравнит "старое" и "новое" значение
    # JSONB-колонки и, так как это буквально один и тот же (уже
    # изменившийся) объект, не увидит разницы и молча не отправит апдейт
    # этого поля в БД — итог: item.content (обычная строка, каждый раз
    # новый объект) обновляется исправно, а properties["messages"]
