"""Что из истории диалога реально уходит в модель.

ЗАМЕР НА БОЕВОЙ БАЗЕ 07.10, диалог «Тренировки» (446 сообщений, живёт с
августа, каждая тренировка дописывается в таблицу):

    ты написал              101 сообщение      2 922 символа
    ассистент ответил       223                19 437
    результаты инструментов 122               273 103   ← 93%

    из них get_table        21 вызов          152 958
            list_all_items   1 вызов           57 850

И это пересылалось заново на КАЖДЫЙ вызов модели. По логам:

    Токены за ход: 107 420 входных
    Токены за ход: 440 636
    Токены за ход: 731 404     ← один ход на «16кг 10 раз»

Около 115 тысяч токенов в одном вызове при окне mistral-small в 128K.
Модель отвечала на пределе — и отвечала плохо: двадцать одна разная
версия одной и той же таблицы в контексте, между ними системный промпт
где-то в самом начале. Жалоба владельца была ровно такая: «оч странно он
отвечает».

ВТОРОЙ СЛУЧАЙ, 10.10: диалог «Telegram» умер насовсем. 26.09 на «найди
мои права» ушло три get_file подряд, каждый с base64 файла целиком —
1.5, 3.8 и 1.9 МБ. Mistral ответил 400. Запись починили сразу (_mcp_*
отрезаются до сохранения), но отравленные записи остались лежать, а
история проигрывается модели заново КАЖДЫЙ ход: через две недели человек
написал в тот же чат «а что такое Кейтерка?» и получил ту же ошибку.
Отсюда второе правило — потолок на один результат, независимо от
возраста: он действует на чтении, поэтому лечит и уже отравленное.

РЕШЕНИЕ. Старые ОБЪЁМНЫЕ результаты инструментов заменяются короткой
заглушкой в том, что отправляется модели, а непомерные обрезаются по
потолку даже в самом свежем ходу. Три вещи, за которые здесь
стоит держаться:

1. Ничего не удаляется. Запись остаётся в БД, в истории диалога и на
   экране; меняется только содержимое запроса к LLM. Ручное сжатие (ТЗ
   §10a, dialog_compaction.py) со снапшотами и откатом — по-прежнему
   единственное, что трогает сами данные. Здесь отката не нужно, потому
   что нечего откатывать.

2. Само сообщение роли "tool" остаётся на месте — сворачивается только
   его текст. У каждого assistant.tool_calls[i].id должен быть парный
   tool-результат, иначе Mistral отвечает 400 (та же причина, по которой
   find_cut_index в dialog_compaction.py режет историю только по границе
   user-реплики).

3. Маленькие результаты не сворачиваются НИКОГДА, даже древние. Именно
   в них лежат id, которыми модель адресует строки и записи: результат
   add_table_row — это ~200 символов и row_id внутри. Свернуть его —
   значит заставить модель снова звать get_table, то есть вернуть ту же
   проблему с другой стороны. Дорого не количество результатов, а дампы:
   свернув то, что больше _FOLD_OVER_CHARS, мы убираем из примера выше
   ~240 тысяч символов из 273 и не теряем ни одного id.
"""

from __future__ import annotations

# Сколько последних ходов пользователя остаются дословно. Четыре, а не
# один: модель часто ссылается на то, что нашла ход-два назад («добавь
# это в ту же таблицу»), и обрывать такую связь ради ещё нескольких
# тысяч символов невыгодно.
KEEP_LAST_TURNS = 4

# Порог «объёмного» результата. 600 символов — выше любого ответа-
# подтверждения (add_table_row с row_id укладывается в ~250, update — в
# ~350) и много ниже любого дампа (get_table в том же диалоге — 7–9 тысяч).
FOLD_OVER_CHARS = 600

# Потолок на ОДИН результат, независимо от возраста.
#
# Свёртки выше недостаточно: она щадит последние ходы, а убить запрос
# может один результат в самом свежем. Живой случай 10.10 — диалог
# «Telegram» умер НАСОВСЕМ. 26.09 на «найди мои права» ушло три get_file
# подряд, и в каждом результате лежал ключ _mcp_resource с base64 файла
# целиком: 1.5, 3.8 и 1.9 МБ. Это 7.26 МБ в одном ходу — Mistral ответил
# 400, ассистент сказал «не получилось, попробуй позже».
#
# Запись в промпт починили тогда же (_mcp_* отрезаются до сохранения,
# routers/dialogs.py), но этого МАЛО, и вот почему: история диалога
# проигрывается модели заново на каждом ходу. Отравленные записи
# остались лежать, и 10.10 человек написал в тот же чат «а что такое
# Кейтерка?» — и снова получил ту же ошибку, через две недели после
# «исправления». Диалог нельзя было ни продолжить, ни починить изнутри.
#
# Поэтому потолок здесь, на ЧТЕНИИ: он лечит уже отравленные диалоги
# задним числом и закрывает весь класс отказов разом — какой бы тул ни
# вернул мегабайт, в промпт он не попадёт.
#
# 30 000 символов (~8.5 тысяч токенов) — с запасом над всем, что
# инструменты отдают по делу (самый крупный законный результат в живой
# базе: list_all_items, 57 850 — он обрежется, и это правильная цена).
MAX_RESULT_CHARS = 30_000


def _stub(name: str | None, size: int) -> str:
    """Заглушка вместо свёрнутого результата.

    Говорит модели три вещи: что здесь был результат, какого инструмента
    и что данные могли устареть. Последнее важнее всего: до этой правки
    модель видела двадцать одну версию таблицы за два месяца и не имела
    никакого признака, какая из них актуальна.
    """
    tool = name or "инструмента"
    return (
        f'{{"_свёрнуто": "здесь был результат {tool} ({size} симв.), убран из контекста '
        'как устаревший — данные с тех пор могли измениться. Нужны актуальные — вызови '
        'инструмент снова."}'
    )


def _truncate(content: str, limit: int) -> str:
    """Обрезать с явной пометкой, что это обрезок, а не всё.

    Пометка обязательна и обязана быть человеческим текстом: без неё
    модель принимает обрубленный JSON за полный результат и отвечает по
    половине данных, не сказав об этом.
    """
    return (
        content[:limit]
        + f'\n\n[ОБРЕЗАНО: показано {limit} символов из {len(content)}. '
        "Результат слишком велик для контекста — если нужного здесь нет, "
        "запроси конкретный элемент или уточни запрос.]"
    )


def fold_stale_tool_results(
    records: list[dict],
    *,
    keep_last_turns: int = KEEP_LAST_TURNS,
    fold_over_chars: int = FOLD_OVER_CHARS,
    max_result_chars: int = MAX_RESULT_CHARS,
) -> list[dict]:
    """Копия истории, в которой объёмные старые tool-результаты свёрнуты.

    Исходный список не меняется: он же уходит в БД и на экран.
    """
    if not records:
        return records

    # Граница окна — начало keep_last_turns-го с конца хода пользователя.
    # Ход = реплика пользователя и всё, что за ней последовало.
    boundary = 0
    seen = 0
    for i in range(len(records) - 1, -1, -1):
        if records[i].get("role") == "user":
            seen += 1
            if seen >= keep_last_turns:
                boundary = i
                break

    folded: list[dict] = []
    for i, record in enumerate(records):
        content = record.get("content") or ""
        if record.get("role") != "tool":
            folded.append(record)
            continue
        # Старое и объёмное — заглушкой.
        if i < boundary and len(content) > fold_over_chars:
            folded.append({**record, "content": _stub(record.get("name"), len(content))})
            continue
        # Свежее, но непомерное — обрезаем. Потолок действует всегда:
        # именно свежий мегабайтный результат убивал ход целиком.
        if len(content) > max_result_chars:
            folded.append({**record, "content": _truncate(content, max_result_chars)})
            continue
        folded.append(record)
    return folded
