"""Запись действий в аудит.

События и так печатаются в лог, но этого мало: docker крутит логи по
10 МБ × 3, то есть след живёт дни, а вопрос «кто и когда подключался к
моей базе» задают через месяцы. Плюс в логе всё вперемешку с
access-строками и ищется только grep'ом.

ТРИ ПРАВИЛА, каждое куплено отдельной опасностью.

1. Аудит НИКОГДА не роняет запрос. Упавшая запись следа — не повод не
   отдать человеку его заметку: любая ошибка глотается с логом.

2. В аудит не попадает содержимое. Ни текста заметок, ни аргументов
   инструментов, ни самих токенов — только имя события и идентификаторы.
   Иначе аудит станет вторым местом, где лежат личные данные, и защищать
   придётся уже его.

3. Неудачные попытки пишутся с ПОТОЛКОМ. Иначе перебор токенов
   превращается в запись строки на каждую попытку — то есть в способ
   раздуть базу чужими руками, ровно противоположный смыслу защиты.
"""

from __future__ import annotations

import logging

from sqlalchemy.ext.asyncio import AsyncSession

from app.models import AuditLog
from app.rate_limit import rate_limited

logger = logging.getLogger(__name__)

# Имена событий. Строками не разбрасываемся: опечатка в имени означает
# запись, которую потом никто не найдёт фильтром.
MCP_TOOL = "mcp.tool"
MCP_AUTH_FAILED = "mcp.auth_failed"
MCP_TOKEN_CREATED = "mcp.token.created"
MCP_TOKEN_REVOKED = "mcp.token.revoked"
OAUTH_CLIENT_REGISTERED = "oauth.client.registered"
OAUTH_GRANTED = "oauth.granted"
OAUTH_DENIED = "oauth.denied"
OAUTH_CONNECTION_REVOKED = "oauth.connection.revoked"
OAUTH_CODE_REPLAY = "oauth.code.replay"
OAUTH_REFRESH_REPLAY = "oauth.refresh.replay"
# Использование токена, который уже отозвали. Отдельное событие, а не
# «просто не подошёл»: отозванный токен не может «случайно» оказаться у
# клиента — значит копию сохранили и пробуют.
MCP_TOKEN_REVOKED_USED = "mcp.token.revoked_used"

# Сколько неудачных попыток с одного источника записываем за час. Перебор
# всё равно упирается в ограничение частоты (app/rate_limit.py); аудиту
# достаточно зафиксировать, что попытки были, и откуда.
FAILED_ATTEMPTS_PER_HOUR = 10


async def record(
    db: AsyncSession,
    *,
    event: str,
    user_id=None,
    subject: str = "",
    source: str = "",
    details: dict | None = None,
    commit: bool = False,
) -> None:
    """Записать событие. Никогда не бросает наружу.

    Пишем В ТУ ЖЕ сессию, что и само действие. Первая версия брала свою —
    и след разъезжался с тем, что он описывает: действие могло откатиться,
    а запись о нём остаться (и наоборот). Заодно это ломало тесты, которые
    работают внутри одной откатываемой транзакции.

    commit=True — для случаев, когда следом полетит исключение и обычного
    коммита не будет. Ровно один такой: неудачная попытка входа. Её надо
    сохранить ИМЕННО потому, что запрос закончится 401.
    """
    if event == MCP_AUTH_FAILED and rate_limited(
        f"audit-fail:{source}", max_requests=FAILED_ATTEMPTS_PER_HOUR, window_seconds=3600
    ):
        return

    try:
        db.add(AuditLog(
            user_id=user_id,
            event=event,
            subject=str(subject)[:255],
            source=str(source)[:64],
            details=details or {},
        ))
        if commit:
            await db.commit()
    except Exception:
        # Ровно то, ради чего эта обёртка и существует: упавшая запись
        # следа не должна отнимать у человека ответ.
        logger.warning("Не удалось записать событие аудита %s", event, exc_info=True)


# --- события, ради которых человека действительно стоит дёрнуть ---------
#
# Список короткий НАМЕРЕННО. Уведомление о том, что обычно безобидно, учит
# смахивать не глядя — и тогда настоящее тоже смахнут. Поэтому сюда
# попадает только то, что (а) редко, (б) человек не делал сам, (в) требует
# от него действия.
#
# Чего здесь нет и почему.
#
# Вызовы инструментов — их сотни, это спам.
#
# Выдача токена и согласие на доступ — человек только что сделал это сам,
# своей же сессией; сообщать ему о его же действии бессмысленно.
#
# ПЕРЕБОР ТОКЕНОВ — отдельный случай, и решение против уведомления далось
# не сразу. Записать его в аудит мы можем, а вот КОГО предупреждать —
# неизвестно: у неудачной попытки нет пользователя, токен-то не подошёл.
# Слать всем значит дёргать семью фоновым шумом интернета — ровно та
# усталость, ради борьбы с которой этот список и держат коротким. Поэтому
# перебор остаётся в журнале (его видно фильтром) и упирается в
# ограничение частоты, но никого не будит.
ALERT_TITLES: dict[str, tuple[str, str]] = {
    OAUTH_CODE_REPLAY: (
        "Подозрительная активность: код авторизации использован дважды",
        "Кто-то попытался повторно обменять код доступа. Доступ этого приложения отозван — "
        "подключите его заново, если это были вы.",
    ),
    OAUTH_REFRESH_REPLAY: (
        "Подозрительная активность: токен доступа использован дважды",
        "Похоже, у кого-то есть копия токена. Подключение отозвано целиком — "
        "подключите приложение заново, если это были вы.",
    ),
    MCP_TOKEN_REVOKED_USED: (
        "Отозванным токеном пытались воспользоваться",
        "Токен MCP отозван, но кто-то попробовал им зайти. Значит копия осталась у него. "
        "Проверьте список подключений в настройках.",
    ),
}

# Не чаще раза в час на событие. Один инцидент — это десятки попыток
# подряд; без задержки человек получил бы вместо предупреждения поток.
ALERT_COOLDOWN_SECONDS = 3600


async def alert(db: AsyncSession, *, event: str, user_id, subject: str = "", source: str = "") -> None:
    """Записать событие И показать его человеку.

    Сначала запись, потом уведомление: даже если уведомление не дойдёт
    (нет подписки, нет Telegram), след должен остаться.
    """
    from app.models import Notification

    await record(db, event=event, user_id=user_id, subject=subject, source=source)

    if user_id is None or event not in ALERT_TITLES:
        return
    if rate_limited(f"alert:{user_id}:{event}", max_requests=1, window_seconds=ALERT_COOLDOWN_SECONDS):
        return

    title, body = ALERT_TITLES[event]
    try:
        db.add(Notification(user_id=user_id, type="security", title=title, body=body,
                            payload={"event": event, "subject": str(subject)}))
    except Exception:
        logger.warning("Не удалось поставить уведомление о %s", event, exc_info=True)
