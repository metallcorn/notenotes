"""Тема, где ошибка дорого стоит — по СМЫСЛУ, а не по списку слов.

Почему не список слов. Он был, и он провалился дважды подряд:

  - «Собираюсь в Черногорию на 10 дней. Что нужно с документами?» и
    «надо заново замельдоваться» темой НЕ считались, то есть вся защита к
    ним просто не применялась;
  - после того как я дописал недостающие слова, замер сдвинулся с 3,3,3
    всего до 3,3,4 — «30 дней» по-прежнему выдумывалось.

И главное возражение, которое важнее обоих замеров: список слов не
масштабируется. Спросят на английском или польском — не сработает.
Появится новая тема — дописывать десятки слов. Сформулируют иначе — мимо.
Дописывать по слову на каждый случай значит вечно чинить хвосты.

Здесь тема задаётся ОПИСАНИЕМ, а не перечнем, и сравнивается по смыслу
тем же многоязычным эмбеддером, что уже работает в семантическом поиске.
Он находил заметки про Citroën по запросу «проблемы с машиной», где этого
слова нет вовсе. Новая тема — это одна фраза, а не сотня слов, и она
работает на любом языке без перевода.

Цена: один вызов эмбеддера на сообщение. Он в разы дешевле чат-вызова,
который всё равно происходит следом, и заметно быстрее.
"""

from __future__ import annotations

import logging
import math

logger = logging.getLogger(__name__)

# Описания тем — по одной фразе на область. Пишутся на русском, но модель
# многоязычная: вопрос на английском или польском ложится рядом с той же
# фразой. Добавить область = добавить строку, а не словарь форм.
HIGH_STAKES_ANCHORS: tuple[str, ...] = (
    "вопрос о лекарстве, дозировке, симптомах, лечении или обращении к врачу",
    "вопрос о документах, визе, виде на жительство, прописке, гражданстве или "
    "пересечении границы",
    "экстренная ситуация: вызов скорой помощи, полиции, спасателей",
    "вопрос о цене, стоимости, штрафе, налоге, пошлине или сумме денег",
)

# Описания БЫТОВЫХ тем — не для красоты симметрии, а потому что без них
# классификатор не работает. Измерено: при сравнении только с «дорогими»
# наборы ПЕРЕКРЫВАЛИСЬ (худший дорогой 0.650 против лучшего бытового
# 0.759), и хуже всего доставалось английским вопросам — они получали
# меньше просто потому, что описания на русском. Это языковой сдвиг, а не
# сигнал темы.
#
# Сравнение с ДВУМЯ наборами сокращает сдвиг: он одинаково влияет на обе
# близости и уходит в разности. После этого наборы разделились полностью,
# включая вопросы на английском и польском, к которым не добавлено ни
# одного слова.
EVERYDAY_ANCHORS: tuple[str, ...] = (
    "список покупок, продукты, рецепт, приготовление еды",
    "напоминание о бытовом деле, встрече или домашней задаче",
    "поиск моей заметки, файла или записи в приложении",
    "ремонт и обслуживание автомобиля, техника, запчасти",
    "знакомство с приложением, как им пользоваться",
)

# Порог по РАЗНОСТИ близостей, измеренный на 16 реальных примерах — тех,
# на которых список слов промахивался, и бытовых из других сценариев:
#
#   дорогие:  +0.024 … +0.143  (включая англ. +0.101, польск. +0.076)
#   бытовые:  −0.160 … −0.017
#
# Разделение полное, граница около нуля. Взят небольшой положительный
# сдвиг: цена ошибки несимметрична, но не так сильно, как кажется —
# ложное срабатывание это лишний абзац в промпте и, возможно, один
# лишний вызов LLM, поэтому нулём не рискуем ради пары сотых.
SIMILARITY_MARGIN = 0.01

_anchor_vectors: tuple[list[list[float]], list[list[float]]] | None = None


def _cosine(a: list[float], b: list[float]) -> float:
    dot = sum(x * y for x, y in zip(a, b))
    na = math.sqrt(sum(x * x for x in a))
    nb = math.sqrt(sum(y * y for y in b))
    return dot / (na * nb) if na and nb else 0.0


async def is_high_stakes_topic(text: str) -> bool:
    """Похож ли разговор на «дорогую» тему.

    Ошибка эмбеддера (нет ключа, сеть, лимит) НЕ роняет ход и НЕ включает
    защиту: разговор проходит как обычный. Обратный выбор — считать всё
    «дорогим» при сбое — сделал бы ассистента бесполезно-осторожным
    ровно тогда, когда он и так работает хуже.
    """
    global _anchor_vectors

    text = (text or "").strip()
    if len(text) < 10:
        return False

    from app.embeddings import embed_texts

    try:
        if _anchor_vectors is None:
            stakes = await embed_texts(list(HIGH_STAKES_ANCHORS))
            everyday = await embed_texts(list(EVERYDAY_ANCHORS))
            _anchor_vectors = (stakes, everyday)
        vector = (await embed_texts([text]))[0]
    except Exception:
        logger.warning("Не удалось определить тему по смыслу — считаю обычной", exc_info=True)
        return False

    stakes_vectors, everyday_vectors = _anchor_vectors
    stakes_score = max(_cosine(vector, a) for a in stakes_vectors)
    everyday_score = max(_cosine(vector, a) for a in everyday_vectors)
    return (stakes_score - everyday_score) >= SIMILARITY_MARGIN
