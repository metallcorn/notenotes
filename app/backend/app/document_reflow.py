from __future__ import annotations

import logging

from app.core.config import get_settings
from app.llm.base import Message
from app.llm.factory import get_llm_client

logger = logging.getLogger(__name__)

_MAX_CHARS = 8000

# Реальная жалоба: один и тот же вызов, который ОДНОВРЕМЕННО читает текст И
# раскладывает его по вёрстке (vision.py._PROMPT), делает это ненадёжно —
# паспорт то получался аккуратной таблицей, то плоским потоком строк, без
# видимой системной причины (проверено на живых документах пользователя).
# Разделение на два шага осознанное и подтверждённое пользователем: сначала
# ТОЛЬКО прочитать (уже работает — vision.py/PyMuPDF), потом ОТДЕЛЬНЫМ
# вызовом с ОДНОЙ задачей — переформатировать уже известный текст ближе к
# оригинальной вёрстке — надёжнее, чем просить всё сразу. Цена — лишний
# LLM-вызов на каждый документ/страницу, принято пользователем осознанно.
_PROMPT = (
    "Тебе дан текст, извлечённый из документа механически (OCR фото/скана "
    "или текстовый слой PDF) — порядок может быть перепутан: колонки идут "
    "вперемешку построчно, пары «поле-значение» разбиты на отдельные "
    "строки вместо одной строки/ячейки, таблица распалась на голый список "
    "фрагментов и т.п., потому что механическое извлечение не понимает "
    "визуальную вёрстку оригинала.\n\n"
    "Переформатируй в чистый Markdown, МАКСИМАЛЬНО близкий по структуре к "
    "оригинальному документу:\n"
    "- настоящие таблицы — markdown-таблицами (| ... | ... |);\n"
    "- пары «поле-значение» (формы, паспорта, ID-карты, билеты, "
    "удостоверения) — тоже таблицей «Поле | Значение» или явным списком "
    "«Поле: значение», НЕ голым потоком «подпись поля» на одной строке и "
    "«значение» на следующей;\n"
    "- текст в несколько колонок — сначала целиком одна колонка, потом "
    "другая, не перемешивай абзацы построчно между колонками;\n"
    "- обычный связный текст (письмо, договор одной колонкой и т.п.) — "
    "оставь как есть, просто убери артефакты построчного извлечения "
    "(лишние переносы посреди предложений и т.п.).\n\n"
    "КРИТИЧНО: содержание должно остаться ДОСЛОВНО тем же — меняй только "
    "порядок и оформление, ни одного слова/числа/строки не теряй и не "
    "выдумывай. Если неясно, к какому полю/колонке относится кусок текста "
    "— оставь его отдельной строкой как есть, не гадай, куда его "
    "пристроить, лучше нераспределённый кусок, чем придуманная связь.\n\n"
    "Ответь ТОЛЬКО результатом в Markdown, без вступлений, пояснений и "
    "без обёртки в code fence (```) — сам текст не программный код."
)


def _strip_outer_fence(text: str) -> str:
    # Реальный найденный случай: модель иногда оборачивает ВЕСЬ ответ в
    # один большой ``` code fence (видимо, чтобы сохранить моноширинную
    # разметку MRZ-зоны паспорта) — тогда таблицы/списки внутри рендерятся
    # как голый текст, а не как markdown. Снимаем только ВНЕШНИЙ фенс,
    # содержимое внутри не трогаем.
    lines = text.split("\n")
    if len(lines) >= 2 and lines[0].startswith("```") and lines[-1].strip() == "```":
        return "\n".join(lines[1:-1]).strip()
    return text


def _split_into_chunks(raw: str, max_chars: int) -> list[str]:
    """Реальный найденный баг: raw[:_MAX_CHARS] молча ОБРЕЗАЛ документ —
    для 24-страничного regulamin'а это значило "причёсаны первые ~5
    страниц, остальные 19 исчезли без следа" (transcription_status при
    этом всё равно "done", никакой видимой ошибки). КРИТИЧНО из промпта
    выше ("ни одного слова не теряй") нарушалось на уровне ДО модели, не
    ею. Бьём на куски по границам абзацев (не жёстко по символам — не
    разрубать предложение/таблицу посередине без крайней необходимости),
    каждый прогоняем через reflow отдельно — дороже (несколько LLM-вызовов
    на длинный документ вместо одного), но ничего не теряет."""
    if len(raw) <= max_chars:
        return [raw]
    chunks: list[str] = []
    current = ""
    for paragraph in raw.split("\n\n"):
        candidate = f"{current}\n\n{paragraph}" if current else paragraph
        if len(candidate) > max_chars and current:
            chunks.append(current)
            current = paragraph
        else:
            current = candidate
        # Один абзац сам по себе длиннее лимита (гигантская таблица) —
        # не оставляем его целиком непричёсанным, режем жёстко по символам,
        # это крайний случай, а не типичный путь.
        while len(current) > max_chars:
            chunks.append(current[:max_chars])
            current = current[max_chars:]
    if current:
        chunks.append(current)
    return chunks


async def _reflow_chunk(client, raw: str) -> str:
    try:
        response = await client.chat(
            [
                Message(role="system", content=_PROMPT),
                Message(role="user", content=raw),
            ],
            [],
        )
    except Exception:
        logger.exception("Ошибка причёсывания вёрстки документа")
        return raw

    reflowed = _strip_outer_fence(response.message.content.strip())
    return reflowed or raw


async def reflow_document_text(raw: str) -> str:
    """Второй, отдельный LLM-проход поверх уже извлечённого/распознанного
    текста (не вместо OCR/PyMuPDF-извлечения, а ПОСЛЕ) — только причёсывает
    вёрстку, не читает текст заново. При любой ошибке или пустом ключе —
    отдаёт исходный текст как есть, это улучшение, а не обязательный шаг.
    Длинные документы бьются на куски (см. _split_into_chunks) — каждый
    прогоняется через reflow отдельно, ни один не отбрасывается."""
    settings = get_settings()
    if not settings.llm_api_key or not raw.strip():
        return raw

    client = get_llm_client()
    chunks = _split_into_chunks(raw, _MAX_CHARS)
    reflowed_chunks = [await _reflow_chunk(client, chunk) for chunk in chunks]
    return "\n\n".join(reflowed_chunks)
