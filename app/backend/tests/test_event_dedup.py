"""Одно событие, попавшее в базу дважды.

Живой случай 10.10: утренняя сводка пришла двумя строками про один
собачий марш —

    📌 11:00 Marsz Kejterka в Познани — 🐕 Marsz Kejterka уже в субботу
    📌 11:00 Марш Кейтерка в Познани  — 🐕 В Познани снова пройдёт Марш

poznan.pl написал о событии дважды, разными статьями; одна заметка
по-польски, другая по-русски.
"""

from __future__ import annotations

import pytest

from app.event_dedup import SAME_EVENT_RATIO, normalize_title, same_event


class TestПохожестьНазваний:
    @pytest.mark.parametrize("a,b", [
        ("Marsz Kejterka в Познани", "Марш Кейтерка в Познани"),
        ("Налоги 08-2026", "Налоги 08-2026"),
        ("Wizyta WUMP — Libelta 16/20", "Визит в WUMP — Libelta 16/20"),
        ("Срок истекает 10.12: Сервисная книжка", "Срок истекает 10.12: Сервисная книжка (копия)"),
        ("ОПЛАТИТЬ ZUS", "оплатить zus"),
    ])
    def test_одно_и_то_же(self, a, b):
        assert same_event(a, b)

    @pytest.mark.parametrize("a,b", [
        ("Встреча с врачом", "Забрать посылку"),
        ("Рейс FR1234 Познань–Вильнюс", "Стоматолог"),
        # Самый близкий из «разных» в замере: 0.769, порог 0.85.
        ("Фестиваль пива", "Фестиваль кино"),
        ("Оплатить ZUS", "Оплатить интернет"),
        ("Забрать права", "Забрать посылку"),
        ("Маникюр", "Массаж"),
    ])
    def test_разные_события(self, a, b):
        assert not same_event(a, b)

    def test_порог_в_замеренном_зазоре(self):
        """Между худшим дубликатом (0.863) и худшим «разным» (0.769).
        Если кто-то соберётся двигать порог — пусть сначала сломает этот
        тест и перемерит на живых названиях, а не на интуиции."""
        assert 0.78 < SAME_EVENT_RATIO < 0.86

    def test_латиницу_не_переводим_в_кириллицу(self):
        """Обратное направление даёт мусор («wизйта wумп») и роняет
        похожесть настоящего дубликата ниже порога."""
        assert normalize_title("Wizyta WUMP — Libelta 16/20") == "wizyta wump libelta 16 20"

    def test_пустые(self):
        assert same_event("", "")
        assert not same_event("", "Встреча")
