"""Просроченная дата, поданная как действующая.

Реальный случай (диалог про замену прав, 2026-09-09): пользователь прислал
данные мельдунка, ассистент прочитал срок и ответил «Твоя текущая прописка
действительна до 14 июня 2026 года. Для замены прав этот адрес подходит».
Дело было 9 сентября — прописка кончилась почти три месяца назад.
Пользователь заметил сам, но мог и не заметить: пошёл бы подавать
документы с недействительной бумагой.

Текущая дата у модели в промпте есть с 2026-09-03 — она её просто не
сравнила. Ровно тот случай, когда полагаться на рассуждение нельзя, а
проверить арифметику кодом дёшево.
"""

from datetime import date

import pytest

from app.expiry_check import find_expired_claims

TODAY = date(2026, 9, 9)


def test_the_real_case_is_caught():
    text = "Твоя текущая прописка **действительна до 14 июня 2026 года** по адресу…"
    assert find_expired_claims(text, TODAY) == [date(2026, 6, 14)]


@pytest.mark.parametrize(
    "text,expected",
    [
        ("Ważna do 14 czerwca 2026", date(2026, 6, 14)),
        ("Документ valid until 2026-01-15", date(2026, 1, 15)),
        ("Срок действия до 01.03.2026, обратитесь заранее", date(2026, 3, 1)),
        ("Годна до 28.02.2026", date(2026, 2, 28)),
    ],
)
def test_formats_and_languages(text, expected):
    """Документы приходят на русском, польском и английском — и датами в
    трёх разных начертаниях."""
    assert find_expired_claims(text, TODAY) == [expected]


@pytest.mark.parametrize(
    "text",
    [
        "Карта побыту действительна до 20.12.2027",
        "Полис действителен до 31 декабря 2026",
        # Ровно сегодня — ещё действует, а не «просрочено вчера».
        "Годен до 2026-09-09",
    ],
)
def test_future_and_today_are_not_flagged(text):
    assert find_expired_claims(text, TODAY) == []


@pytest.mark.parametrize(
    "text",
    [
        # Прошедшая дата БЕЗ формулировки срока — обычный факт из прошлого.
        "Встреча была 14 июня 2026, всё прошло хорошо",
        "Договор подписан 01.02.2026",
        "Заметка создана 2026-03-05",
    ],
)
def test_plain_past_dates_are_not_flagged(text):
    """Помечать каждую прошедшую дату — шум, который научит игнорировать
    пометку вообще. Реагируем только на заявленный СРОК ДЕЙСТВИЯ."""
    assert find_expired_claims(text, TODAY) == []


def test_several_documents_in_one_answer():
    text = (
        "Карта побыту действительна до 20.12.2027, "
        "а мельдунек действителен до 14 июня 2026 и страховка ważna do 01.01.2026."
    )
    assert find_expired_claims(text, TODAY) == [date(2026, 6, 14), date(2026, 1, 1)]


def test_impossible_date_does_not_crash():
    """Модель могла ошибиться в самой дате — сравнивать нечего, но и падать
    не за что."""
    assert find_expired_claims("действительна до 31.02.2026", TODAY) == []
