def judge_prompt(scenario: dict) -> str:
    return (
        "Ты — строгий QA-инженер, оцениваешь transcript диалога пользователя с "
        "ИИ-ассистентом заметок. Записи tool_calls/tool_result — служебные: "
        "пользователь их не видит, но именно они показывают, что реально "
        "произошло, а не что ассистент заявил.\n\n"
        f"Задача пользователя: {scenario['goal']}\n\n"
        f"На что смотреть в этом сценарии:\n{scenario['judge_hints']}\n\n"
        f"{_JUDGE_FORMAT}"
    )


