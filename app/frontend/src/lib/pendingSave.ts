/**
 * Можно ли записать накопленное «несохранённое» на сервер.
 *
 * Вынесено из NoteEditor отдельной чистой функцией не ради красоты, а
 * потому что это единственное место, где решается судьба содержимого
 * заметки, — а сам редактор (TipTap/ProseMirror) юнит-тестами намеренно не
 * покрыт, он требует Playwright. Правило должно быть проверяемым.
 *
 * ПОЧЕМУ ТОЛЬКО ЮНИТ-ТЕСТ, БЕЗ E2E. Попытка воспроизвести гонку в реальном
 * браузере (Playwright) не удалась, и это стоит знать, прежде чем пробовать
 * снова. Что выяснилось за шесть заходов:
 *   - page.goto() перезагружает страницу целиком и гонки не создаёт вовсе:
 *     тест оставался зелёным даже с намеренно сломанной проверкой ниже;
 *   - /collab — это ВЕБСОКЕТ, page.route его не перехватывает; а
 *     routeWebSocket перехватывает, но для страницы сокет выглядит
 *     открытым, и посев документа (он идёт на клиенте, серверных сообщений
 *     не ждёт) спокойно завершается — то есть задержать инициализацию так
 *     не получается;
 *   - судя по логам инцидента, PATCH ушёл РАНЬШЕ вебсокета: настоящее окно
 *     живёт внутри одного-двух тактов React, и снаружи браузера попасть в
 *     него детерминированно нечем.
 * Зелёный тест, который ничего не ловит, хуже отсутствующего, поэтому
 * такого теста здесь нет. Надёжный путь, если понадобится, — не e2e, а
 * компонентный тест NoteEditor с подменённым редактором.
 *
 * Реальная потеря данных (2026-09-08, две заметки, второй раз за двое
 * суток). Пользователь быстро переключался между заметками: открыл одну,
 * через 567 мс ушёл на другую — и «досохранение при переключении»
 * немедленно записало на сервер ПУСТОЕ содержимое, потому что документ ещё
 * догружался (GET /collab пришёл уже ПОСЛЕ этого PATCH). Заметка на 2228
 * символов обнулилась. Дебаунс автосейва в 1200 мс тут не помогает —
 * досохранение по замыслу срабатывает мгновенно.
 */
export type PendingSave = { id: string; title: string; content: string } | null;

export function shouldFlushPendingSave(
  pending: PendingSave,
  /** Заметка, для которой загрузка ПОЛНОСТЬЮ завершилась. */
  initializedItemId: string | null,
  /** Доступно обновление приложения — писать нельзя, схема могла измениться. */
  updateAvailable: boolean,
): boolean {
  if (!pending) return false;
  if (updateAvailable) return false;
  // Сердце защиты: сохраняем только то, что относится к ДОГРУЖЕННОЙ
  // заметке. Пока загрузка не завершилась, содержимое редактора — это
  // переходное состояние (часто пустое), а не данные пользователя.
  return pending.id === initializedItemId;
}
