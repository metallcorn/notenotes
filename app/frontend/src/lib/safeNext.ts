/**
 * Куда вернуть человека после входа — с проверкой, что это НАШ адрес.
 *
 * Понадобилось для OAuth (ТЗ §20, подключение по MCP): не вошедшего
 * отправляют на /login?next=/api/oauth/authorize?..., и после входа он
 * должен вернуться туда же, иначе поток обрывается на пустом месте.
 *
 * Почему с проверкой. Значение приходит из адресной строки, то есть от
 * кого угодно: ссылку /login?next=https://фишинг.example можно прислать в
 * письме, человек увидит НАСТОЯЩИЙ домен Notenotes, честно введёт пароль
 * и уедет на чужой сайт уже авторизованным. Это классический открытый
 * редиректор, и он тем опаснее, что страница входа выглядит подлинной —
 * потому что она подлинная.
 *
 * Поэтому берём только путь внутри приложения: начинается с одного «/»
 * и не с «//» (последнее браузер читает как протокол-относительный URL,
 * то есть //evil.example — это другой сайт, а не путь).
 */
export function safeNextPath(raw: string | null): string {
  if (!raw) return "/";
  let value = raw;
  try {
    // Значение обычно приходит закодированным; декодируем, чтобы проверять
    // то же, куда потом пойдём, а не его безопасно выглядящую запись.
    value = decodeURIComponent(raw);
  } catch {
    return "/";
  }
  if (!value.startsWith("/")) return "/";
  if (value.startsWith("//")) return "/";
  // «\» вместо «/» некоторые браузеры трактуют так же — /\evil.example
  // уводил бы на чужой хост.
  if (value.startsWith("/\\")) return "/";
  return value;
}
